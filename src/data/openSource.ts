import type { DataScope, Product, ProductCategory } from '../types/marketplace';

/**
 * Public GitHub projects, listed for reference. Collective AI does not run,
 * vet or support any of them, and none carries an Aegis score (`aegis: null`).
 *
 * Every fact under `openSource` (stars, license, language, last push) was read
 * from the GitHub search API on 2026-11-07; the raw API objects are kept in
 * `openSource.snapshot.json` and the test suite checks the two agree.
 *
 * Selection rules: not archived, pushed on or after 2025-11-07, an OSI-approved
 * license with a real SPDX id (NOASSERTION/OTHER excluded), at least 1,000 stars.
 *
 * Version: `releases/latest` was refused (HTTP 403) in the session that read
 * these facts, so no release tag could be verified and every listing shows
 * the default branch, `main`.
 *
 * Copy: summaries are the repo description in plain words; tags come from the
 * repo's GitHub topics (or the description when the repo has no topics);
 * integrations are only those named in the description or topics.
 */

const CHECKED_AT = '2026-11-07';

interface Facts {
  repo: string;
  license: string;
  stars: number;
  language: string | null;
  pushedAt: string;
}

interface Copy {
  id: string;
  title: string;
  category: ProductCategory;
  summary: string;
  audience: string;
  capabilities: string[];
  inputs: string[];
  outputs: string[];
  integrations: string[];
  scopes: DataScope[];
  tags: string[];
}

function oss(facts: Facts, copy: Copy): Product {
  const version = 'main';
  return {
    ...copy,
    source: 'open-source',
    publisher: 'Open source',
    deployedIn: 'Not run by Collective AI',
    pricing: { model: 'free', amount: 0 },
    aegis: null,
    openSource: {
      repo: facts.repo,
      url: `https://github.com/${facts.repo}`,
      license: facts.license,
      stars: facts.stars,
      language: facts.language ?? 'Mixed',
      pushedAt: facts.pushedAt,
      checkedAt: CHECKED_AT,
    },
    version,
    updated: facts.pushedAt,
    changelog: [{ version, date: facts.pushedAt, note: `Latest push on GitHub as of ${CHECKED_AT}.` }],
  };
}

